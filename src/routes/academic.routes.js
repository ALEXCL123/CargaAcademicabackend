import express, { Router } from 'express';
import * as c from '../controllers/academic.controller.js';
import { requireSession } from './auth.routes.js';

const router = Router();
router.use(['/configuracion','/periodos','/catalogos','/documentos'],requireSession);
router.get('/configuracion',c.config);
router.put('/configuracion',c.editConfig);
router.get('/periodos',c.periods);
router.post('/periodos',c.savePeriod);
router.put('/periodos/:id',c.savePeriod);
router.post('/periodos/:id/activar',c.activatePeriod);
router.post('/periodos/:id/cerrar',c.closePeriod);
router.get('/catalogos/:resource',c.list);
router.post('/catalogos/:resource',c.save);
router.post('/catalogos/asignaturas/ficha',c.saveCourse);
router.put('/catalogos/asignaturas/ficha/:id',c.saveCourse);
router.get('/catalogos/asignaturas/:id/impacto-eliminacion',c.courseDeletionImpact);
router.delete('/catalogos/asignaturas/:id',c.removeCourse);
router.get('/catalogos/:resource/:id',c.detail);
router.put('/catalogos/:resource/:id',c.save);
router.delete('/catalogos/:resource/:id',c.remove);
router.get('/documentos/:id/pdf',c.readPdf);
router.put('/documentos/:id/pdf',express.raw({ type:'application/pdf', limit:'10mb' }),c.uploadPdf);
router.post('/periodos/:period/personal',c.staff);
router.put('/periodos/:period/personal/:id',c.staff);
router.post('/periodos/:period/ofertar',c.offerCourses);
router.put('/periodos/:period/oferta-asignaturas',c.changeCourseOffers);
router.get('/periodos/:period/fusiones',c.fusions);
router.post('/periodos/:period/fusiones',c.authorizeFusion);
router.put('/periodos/:period/fusiones/:id',c.authorizeFusion);
router.delete('/periodos/:period/fusiones/:id',c.removeFusion);
router.get('/periodos/:period/carga',c.readLoad);
router.post('/periodos/:period/carga',c.saveAssignment);
router.put('/periodos/:period/carga/:id',c.saveAssignment);
router.delete('/periodos/:period/carga/:id',c.removeAssignment);
router.post('/periodos/:period/carga-completa',c.completeLoad);
router.get('/periodos/:period/horario',c.readSchedule);
router.post('/periodos/:period/horario/clases-externas',c.saveExternalClass);
router.put('/periodos/:period/horario/clases-externas/:id',c.saveExternalClass);
router.delete('/periodos/:period/horario/clases-externas/:id',c.removeExternalClass);
router.post('/periodos/:period/horario',c.saveSession);
router.put('/periodos/:period/horario/:id',c.saveSession);
router.delete('/periodos/:period/horario/:id',c.removeSession);
router.post('/periodos/:period/propuesta',c.propose);
router.post('/periodos/:period/aplicar-propuesta',c.apply);
router.get('/periodos/:period/reportes/carga',c.previewLoad);
router.get('/periodos/:period/reportes/carga.xlsx',c.exportLoad);
router.get('/periodos/:period/reportes/horario/:career',c.previewSchedule);
router.post('/periodos/:period/reportes/horario/:career/pdf',c.exportSchedule);

export default router;

